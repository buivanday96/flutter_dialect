/// Thrown when code can't be generated for this project.
class GenerationException implements Exception {
  GenerationException(this.message);
  final String message;
  @override
  String toString() => message;
}

class GeneratedApi {
  GeneratedApi(this.files, this.warnings);

  /// Project-relative path → formatted Dart source, in a fixed order.
  final Map<String, String> files;
  final List<String> warnings;
}

/// Generates models + repository for one tag, in the project's style.
class ApiGenerator {
  ApiGenerator(this.ctx);

  final ProjectContext ctx;

  GeneratedApi generate(ApiDoc doc, {required String tag}) {
    final shape = ctx.clientShape;
    if (shape == null) {
      throw GenerationException(
        ctx.client.value == 'api_client'
            ? 'Could not read the API client class in ${ctx.apiClient.value}. '
                  'Set conventions.client to dio or http in .flutterforge.yaml.'
            : 'Could not tell how this project calls HTTP. Set '
                  'conventions.client (dio, http or api_client) in '
                  '.flutterforge.yaml.',
      );
    }
    final ops = doc.operationsFor(tag);
    final warnings = <String>[];
    final feature = snake(tag);
    final targets = _targets(feature, warnings);

    final hand = ctx.models.value;
    if (hand == 'freezed' || hand == 'json_serializable') {
      warnings.add(
        'This project uses $hand models; FlutterForge 0.1 only writes '
        'hand-written models (fromJson/toJson).',
      );
    }
    final codec =
        ctx.jsonMethods.value == 'fromMap/toMap' && hand == 'hand-written'
        ? const JsonCodec(from: 'fromMap', to: 'toMap')
        : const JsonCodec();

    // Keep only operations the client can express.
    final usable = <ApiOperation>[];
    for (final op in ops) {
      final problem = _unsupported(op, shape);
      if (problem == null) {
        usable.add(op);
      } else {
        warnings.add('${op.name}: $problem; skipped.');
      }
    }

    final schemas = _reachable(doc, usable);
    // Only pass on the spec's warnings that concern this tag.
    final opNames = {for (final o in ops) '${o.name} ('};
    warnings.insertAll(0, [
      for (final w in doc.warnings)
        if (opNames.any(w.startsWith) ||
            schemas.any(
              (s) =>
                  s.endsWith('Model') &&
                  w.contains('"${s.substring(0, s.length - 5)}"'),
            ))
          w,
    ]);

    final header =
        '// Generated by FlutterForge from '
        '${doc.title.isEmpty ? 'an OpenAPI spec' : '"${doc.title}"'} '
        '(tag: $tag).\n// Review it, then edit freely: '
        'FlutterForge never overwrites existing files.\n\n';

    final files = <String, String>{};
    files[targets.models] = _format(header + _modelsFile(doc, schemas, codec));

    final repoClass = '${pascal(tag)}Repository';
    final emitter = _RepoEmitter(shape, codec, _nullAwareElements);
    if (targets.interface != null) {
      files[targets.interface!] = _format(
        header +
            _imports(targets.interface!, {targets.models}, const []) +
            emitter.interface(repoClass, usable),
      );
    }
    final repoImports = {
      targets.models,
      if (targets.interface != null) targets.interface!,
      if (shape.kind == 'api_client') shape.path!,
    };
    files[targets.repository] = _format(
      header +
          _imports(targets.repository, repoImports, switch (shape.kind) {
            'dio' => ['package:dio/dio.dart'],
            'http' => ['dart:convert', 'package:http/http.dart as http'],
            _ => const [],
          }) +
          emitter.repository(
            targets.interface != null ? '${repoClass}Impl' : repoClass,
            targets.interface != null ? repoClass : null,
            usable,
          ),
    );
    return GeneratedApi(files, warnings);
  }

  ({String models, String repository, String? interface}) _targets(
    String f,
    List<String> warnings,
  ) {
    final split = ctx.repository.value == 'interface+impl';
    var layout = ctx.layout.value;
    if (layout == null) {
      warnings.add('Folder layout unknown; using flat-feature.');
      layout = 'flat-feature';
    }
    final features = ctx.featuresPath ?? 'lib/features';
    switch (layout) {
      case 'layered-feature':
        return (
          models: '$features/$f/domain/${f}_models.dart',
          interface: split ? '$features/$f/domain/${f}_repository.dart' : null,
          repository: split
              ? '$features/$f/data/${f}_repository_impl.dart'
              : '$features/$f/data/${f}_repository.dart',
        );
      case 'layer-first':
        final models =
            _existingDir(['lib/models', 'lib/model']) ?? 'lib/models';
        final repos = _repositoryDir() ?? 'lib/repositories';
        return (
          models: '$models/${f}_models.dart',
          interface: split ? '$repos/${f}_repository.dart' : null,
          repository: split
              ? '$repos/${f}_repository_impl.dart'
              : '$repos/${f}_repository.dart',
        );
      default:
        return (
          models: '$features/$f/${f}_models.dart',
          interface: split ? '$features/$f/${f}_repository.dart' : null,
          repository: split
              ? '$features/$f/${f}_repository_impl.dart'
              : '$features/$f/${f}_repository.dart',
        );
    }
  }

  String? _existingDir(List<String> candidates) {
    for (final c in candidates) {
      if (ctx.layout.evidence.contains(c)) return c;
    }
    return null;
  }

  /// The folder holding most existing `*_repository.dart` files.
  String? _repositoryDir() {
    final counts = <String, int>{};
    for (final path in ctx.repository.evidence) {
      final dir = p.posix.dirname(path);
      counts[dir] = (counts[dir] ?? 0) + 1;
    }
    if (counts.isEmpty) return null;
    final dirs = counts.keys.toList()
      ..sort((a, b) {
        final c = counts[b]!.compareTo(counts[a]!);
        return c != 0 ? c : a.compareTo(b);
      });
    return dirs.first;
  }

  String? _unsupported(ApiOperation op, ClientShape shape) {
    if (shape.kind != 'api_client') return null;
    final m = shape.methods[op.method];
    if (m == null) return '${shape.className} has no ${op.method}() method';
    if (op.queryParams.isNotEmpty && m.queryParam == null) {
      return '${shape.className}.${op.method}() takes no query parameters';
    }
    if (op.body != null && m.bodyParam == null) {
      return '${shape.className}.${op.method}() takes no request body';
    }
    return null;
  }

  /// Names of every schema [ops] need, sorted.
  List<String> _reachable(ApiDoc doc, List<ApiOperation> ops) {
    final seen = <String>{};
    void visit(ApiType? t) {
      switch (t) {
        case ListType(:final item):
          visit(item);
        case RefType(:final name) when seen.add(name):
          for (final f in doc.schemas[name]!.fields) {
            visit(f.type);
          }
        default:
      }
    }

    for (final op in ops) {
      for (final prm in [...op.pathParams, ...op.queryParams]) {
        visit(prm.type);
      }
      visit(op.body?.type);
      visit(op.response);
    }
    return seen.toList()..sort();
  }

  String _modelsFile(ApiDoc doc, List<String> names, JsonCodec codec) {
    final b = StringBuffer();
    for (final name in names) {
      final s = doc.schemas[name]!;
      b.writeln(s.isEnum ? _enum(s) : _class(s, codec));
    }
    return b.toString();
  }

  String _docs(String? text, [String indent = '']) => text == null
      ? ''
      : '${text.trim().split('\n').map((l) => '$indent/// $l'.trimRight()).join('\n')}\n';

  String _enum(ApiSchema s) {
    final b = StringBuffer(_docs(s.description))..writeln('enum ${s.name} {');
    for (final (i, v) in s.enumValues.indexed) {
      final last = i == s.enumValues.length - 1;
      b.writeln("  ${v.name}('${_escape(v.value)}')${last ? ';' : ','}");
    }
    b
      ..writeln()
      ..writeln('  const ${s.name}(this.value);')
      ..writeln()
      ..writeln('  final String value;')
      ..writeln()
      ..writeln('  static ${s.name} fromValue(String value) =>')
      ..writeln('      values.firstWhere((e) => e.value == value);')
      ..writeln('}');
    return b.toString();
  }

  String _class(ApiSchema s, JsonCodec codec) {
    final arg = codec.from == 'fromMap' ? 'map' : 'json';
    final b = StringBuffer(_docs(s.description))..writeln('class ${s.name} {');
    if (s.fields.isEmpty) {
      b
        ..writeln('  const ${s.name}();')
        ..writeln()
        ..writeln(
          '  factory ${s.name}.${codec.from}(Map<String, dynamic> $arg) => '
          'const ${s.name}();',
        )
        ..writeln()
        ..writeln('  Map<String, dynamic> ${codec.to}() => {};')
        ..writeln('}');
      return b.toString();
    }
    b.writeln('  const ${s.name}({');
    for (final f in s.fields) {
      b.writeln('    ${f.required ? 'required ' : ''}this.${f.name},');
    }
    b
      ..writeln('  });')
      ..writeln()
      ..writeln(
        '  factory ${s.name}.${codec.from}(Map<String, dynamic> $arg) {',
      )
      ..writeln('    return ${s.name}(');
    for (final f in s.fields) {
      final value = codec.decode(
        f.type,
        "$arg['${_escape(f.jsonName)}']",
        nullable: f.nullable,
      );
      b.writeln('      ${f.name}: $value,');
    }
    b
      ..writeln('    );')
      ..writeln('  }')
      ..writeln();
    for (final f in s.fields) {
      b
        ..write(_docs(f.description, '  '))
        ..writeln(
          '  final ${dartTypeOf(f.type, nullable: f.nullable)} ${f.name};',
        );
    }
    b
      ..writeln()
      ..writeln('  Map<String, dynamic> ${codec.to}() => {');
    for (final f in s.fields) {
      final key = "'${_escape(f.jsonName)}'";
      final value = codec.encode(f.type, f.name, nullable: f.nullable);
      b.writeln(
        !f.nullable || f.type is AnyType
            ? '    $key: $value,'
            : _nullAwareElements
            ? '    $key: ?$value,'
            : '    if (${f.name} != null) $key: $value,',
      );
    }
    b
      ..writeln('  };')
      ..writeln('}');
    return b.toString();
  }

  String _imports(String from, Set<String> local, List<String> external) {
    final dart = <String>[];
    final pkg = <String>[];
    final rel = <String>[];
    for (final e in external) {
      (e.startsWith('dart:') ? dart : pkg).add(e);
    }
    for (final target in local) {
      if (target == from) continue;
      if (ctx.imports.value == 'relative') {
        rel.add(p.posix.relative(target, from: p.posix.dirname(from)));
      } else {
        pkg.add('package:${ctx.name}/${target.substring('lib/'.length)}');
      }
    }
    final groups = [dart..sort(), pkg..sort(), rel..sort()];
    final blocks = [
      for (final g in groups)
        if (g.isNotEmpty)
          g.map((i) => "import '${_quoteImport(i)};").join('\n'),
    ];
    return '${blocks.join('\n\n')}\n\n';
  }

  /// `package:http/http.dart as http` → `package:http/http.dart' as http`.
  String _quoteImport(String i) {
    final as = i.indexOf(' as ');
    return as < 0 ? "$i'" : "${i.substring(0, as)}'${i.substring(as)}";
  }

  String _format(String source) {
    final version = _formatterVersion();
    try {
      return DartFormatter(
        languageVersion: version,
        pageWidth: ctx.pageWidth,
      ).format(source);
    } on FormatterException catch (e) {
      throw StateError('Generated code does not parse:\n$e\n\n$source');
    }
  }

  /// `{'k': ?v}` needs Dart 3.8; older projects get `if (v != null)`.
  bool get _nullAwareElements {
    final v = ctx.languageVersion?.split('.').map(int.parse).toList();
    return v != null && (v[0] > 3 || (v[0] == 3 && v[1] >= 8));
  }

  Version _formatterVersion() {
    final latest = DartFormatter.latestLanguageVersion;
    final v = ctx.languageVersion;
    if (v == null) return latest;
    final parts = v.split('.').map(int.parse).toList();
    final project = Version(parts[0], parts[1], 0);
    return project > latest ? latest : project;
  }
}

String _escape(String s) =>
    s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');

/// Writes repository classes for one client shape.
class _RepoEmitter {
  _RepoEmitter(this.shape, this.codec, this.nullAwareElements);

  final ClientShape shape;
  final JsonCodec codec;
  final bool nullAwareElements;

  String get _field => shape.fieldName;

  String interface(String name, List<ApiOperation> ops) {
    final b = StringBuffer('abstract interface class $name {\n');
    for (final (i, op) in ops.indexed) {
      if (i > 0) b.writeln();
      b
        ..write(_opDocs(op))
        ..writeln('  ${_signature(op)};');
    }
    b.writeln('}');
    return b.toString();
  }

  String repository(
    String name,
    String? implementsName,
    List<ApiOperation> ops,
  ) {
    final b = StringBuffer('class $name');
    if (implementsName != null) b.write(' implements $implementsName');
    b.writeln(' {');
    final param = _field.replaceFirst(RegExp(r'^_+'), '');
    switch (shape.kind) {
      case 'http':
        b
          ..writeln('  $name(this.$_field, this._baseUrl);')
          ..writeln()
          ..writeln('  final http.Client $_field;')
          ..writeln('  final Uri _baseUrl;');
      case 'dio':
        b
          ..writeln('  $name(this.$_field);')
          ..writeln()
          ..writeln('  final Dio $_field;');
      default:
        final cls = shape.className!;
        b.writeln(
          shape.singleton != null
              ? '  $name({$cls? $param}) : $_field = $param ?? '
                    '$cls.${shape.singleton};'
              : '  $name(this.$_field);',
        );
        b
          ..writeln()
          ..writeln('  final $cls $_field;');
    }
    for (final op in ops) {
      b
        ..writeln()
        ..write(implementsName == null ? _opDocs(op) : '  @override\n')
        ..writeln('  ${_signature(op)} async {')
        ..write(_body(op))
        ..writeln('  }');
    }
    if (shape.kind == 'http') b.write(_httpHelpers);
    b.writeln('}');
    return b.toString();
  }

  static const _httpHelpers = r'''

  Uri _uri(String path, [Map<String, dynamic>? query]) {
    final base = _baseUrl.path.endsWith('/')
        ? _baseUrl.path.substring(0, _baseUrl.path.length - 1)
        : _baseUrl.path;
    return _baseUrl.replace(
      path: '$base$path',
      queryParameters: query == null || query.isEmpty ? null : query,
    );
  }

  Object? _decode(http.Response response) {
    if (response.statusCode >= 400) {
      throw http.ClientException(
        'HTTP ${response.statusCode}',
        response.request?.url,
      );
    }
    return response.body.isEmpty ? null : jsonDecode(response.body);
  }
''';

  String _opDocs(ApiOperation op) {
    final lines = [
      if (op.summary != null) op.summary!.trim(),
      '`${op.method.toUpperCase()} ${op.path}`',
    ];
    return lines.map((l) => '  /// $l\n').join();
  }

  String _bodyName(ApiOperation op) =>
      op.pathParams.any((x) => x.name == 'body') ? 'requestBody' : 'body';

  String _signature(ApiOperation op) {
    final ret = op.response == null ? 'void' : dartType(op.response!);
    final positional = [
      for (final x in op.pathParams) '${dartType(x.type)} ${x.name}',
      if (op.body != null) '${dartType(op.body!.type)} ${_bodyName(op)}',
    ];
    final named = [
      for (final q in op.queryParams)
        q.required
            ? 'required ${dartType(q.type)} ${q.name}'
            : '${dartTypeOf(q.type, nullable: true)} ${q.name}',
    ];
    final params = [
      ...positional,
      if (named.isNotEmpty) '{${named.join(', ')}}',
    ].join(', ');
    return 'Future<$ret> ${op.name}($params)';
  }

  /// `'/tests/$testId'`
  String _path(ApiOperation op) {
    final b = StringBuffer("'");
    final rest = op.path;
    final re = RegExp(r'\{([^}]+)\}');
    var last = 0;
    for (final m in re.allMatches(rest)) {
      b.write(_escape(rest.substring(last, m.start)));
      final param = op.pathParams.firstWhere((x) => x.jsonName == m[1]);
      final expr = switch (param.type) {
        PrimitiveType(dart: 'String') => 'Uri.encodeComponent(${param.name})',
        RefType(isEnum: true) => '${param.name}.value',
        _ => param.name,
      };
      final next = m.end < rest.length ? rest[m.end] : '';
      b.write(
        expr == param.name && !RegExp(r'[A-Za-z0-9_$]').hasMatch(next)
            ? '\$$expr'
            : '\${$expr}',
      );
      last = m.end;
    }
    b
      ..write(_escape(rest.substring(last)))
      ..write("'");
    return b.toString();
  }

  String? _query(ApiOperation op) {
    if (op.queryParams.isEmpty) return null;
    final http = shape.kind == 'http';
    final entries = [
      for (final q in op.queryParams)
        q.required
            ? "'${_escape(q.jsonName)}': ${_queryValue(q.type, q.name, http)}"
            : nullAwareElements
            ? "'${_escape(q.jsonName)}': "
                  '?${_queryValue(q.type, q.name, http, nullable: true)}'
            : 'if (${q.name} != null) '
                  "'${_escape(q.jsonName)}': ${_queryValue(q.type, q.name, http)}",
    ];
    return '{${entries.join(', ')}}';
  }

  /// With [nullable], [name] may be null and so may the result.
  String _queryValue(
    ApiType t,
    String name,
    bool http, {
    bool nullable = false,
  }) {
    final q = nullable ? '?' : '';
    return switch (t) {
      RefType(isEnum: true) => '$name$q.value',
      DateTimeType() => '$name$q.toIso8601String()',
      ListType(:final item) when http =>
        "$name$q.map((e) => ${_queryValue(item, 'e', true)}).toList()",
      PrimitiveType(dart: 'String') => name,
      _ when http => nullable ? '$name?.toString()' : "'\$$name'",
      _ => name,
    };
  }

  String _body(ApiOperation op) {
    final path = _path(op);
    final query = _query(op);
    final data = op.body == null
        ? null
        : codec.encode(op.body!.type, _bodyName(op));
    final args = <String>[path];
    String call;
    String payload;
    switch (shape.kind) {
      case 'dio':
        if (query != null) args.add('queryParameters: $query');
        if (data != null) args.add('data: $data');
        call = 'await $_field.${op.method}<dynamic>(${args.join(', ')})';
        payload = 'response.data';
      case 'http':
        final uri = query == null ? '_uri($path)' : '_uri($path, $query)';
        final httpArgs = [
          uri,
          if (data != null) ...[
            "headers: const {'Content-Type': 'application/json'}",
            'body: jsonEncode($data)',
          ],
        ];
        call = '_decode(await $_field.${op.method}(${httpArgs.join(', ')}))';
        payload = 'response';
      default:
        final m = shape.methods[op.method]!;
        if (query != null) args.add('${m.queryParam}: $query');
        if (data != null) args.add('${m.bodyParam}: $data');
        call = 'await $_field.${op.method}(${args.join(', ')})';
        payload = 'response${shape.payload}';
    }
    if (op.response == null) {
      return '    $call;\n';
    }
    if (op.envelope && !shape.unwrapsEnvelope) {
      payload = "($payload as Map<String, dynamic>)['data']";
    }
    return '    final response = $call;\n'
        '    return ${codec.decode(op.response!, payload)};\n';
  }
}
